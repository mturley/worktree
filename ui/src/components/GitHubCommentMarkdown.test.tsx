import { afterEach, describe, expect, it } from "vitest"
import { cleanup, render, screen } from "@testing-library/react"
import { MantineProvider } from "@mantine/core"
import GitHubCommentMarkdown from "./GitHubCommentMarkdown"

afterEach(cleanup)

describe("GitHubCommentMarkdown", () => {
  const renderGh = (text: string, props: { imagesAsLinks?: boolean } = {}) =>
    render(<MantineProvider><GitHubCommentMarkdown text={text} {...props} /></MantineProvider>)

  it("renders the HTML GitHub allows", () => {
    const { container } = renderGh("<details>\n<summary>Walkthrough</summary>\n\nThe **body**\n</details>\n\nsmall <sub>print</sub>")
    expect(container.querySelector("details summary")?.textContent).toBe("Walkthrough")
    expect(container.querySelector("details strong")?.textContent).toBe("body")
    expect(container.querySelector("sub")?.textContent).toBe("print")
  })

  it("drops HTML comments", () => {
    const { container } = renderGh("<!-- auto-generated by a bot -->\nHello")
    expect(container.textContent).not.toContain("auto-generated")
    expect(container.textContent).toContain("Hello")
  })

  it("strips scripts, event handlers, styles and frames", () => {
    const { container } = renderGh(
      "<script>alert(1)</script><iframe src=\"https://x.io\"></iframe>" +
      "<p onclick=\"alert(1)\" style=\"position:fixed\">text</p>",
    )
    expect(container.querySelector("script, iframe")).toBeNull()
    const p = screen.getByText("text")
    expect(p.getAttribute("onclick")).toBeNull()
    expect(p.getAttribute("style")).toBeNull()
  })

  it("prefixes ids, so a comment cannot clobber the page's own", () => {
    renderGh("<span id=\"root\">x</span>")
    expect(screen.getByText("x").id).toBe("user-content-root")
  })

  it("turns an HTML image into a link with imagesAsLinks", () => {
    const { container } = renderGh("<img src=\"https://example.com/pixel.png\" alt=\"shot\">", { imagesAsLinks: true })
    expect(container.querySelector("img")).toBeNull()
    expect(screen.getByRole("link", { name: "shot" }).getAttribute("href")).toBe("https://example.com/pixel.png")
  })

  it("keeps single line breaks, as GitHub does in comments", () => {
    const { container } = renderGh("line one\nline two")
    expect(container.querySelector("p br")).not.toBeNull()
  })

  it("is the size of the modal's other bodies, not the notes'", () => {
    const { container } = renderGh("text")
    expect(container.querySelector<HTMLElement>(".worktree-notes")?.style.fontSize).toBe("var(--mantine-font-size-sm)")
  })
})
